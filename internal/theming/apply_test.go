func TestApplyWriteRefusesAReadOnlyTarget(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("XDG_STATE_HOME", dir)
	p := filepath.Join(dir, "foot.ini")
	rendered := "# generated by sysc-shell — do not edit\nok\n"
	if err := ApplyWrite(p, rendered); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(p, 0o444); err != nil {
		t.Fatal(err)
	}
	defer os.Chmod(p, 0o644)
	if err := ApplyWrite(p, rendered+"\n"); err == nil {
		t.Fatal("a read-only target must report the failure, not be renamed over")
	}
	if got, _ := os.ReadFile(p); string(got) != rendered {
		t.Fatalf("read-only target changed: %q", got)
	}
}

