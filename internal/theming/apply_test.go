func TestThemingWritesLeaveNoTempFiles(t *testing.T) {
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	dir := t.TempDir()
	cfg := filepath.Join(dir, "config.kdl")
	gen := filepath.Join(dir, "sysc-shell.kdl")
	ini := filepath.Join(dir, "settings.ini")
	for _, p := range []string{cfg, ini} {
		if err := os.WriteFile(p, []byte("[Settings]\ngtk-theme-name=sysc-shell-Old\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	rendered := "// generated by sysc-shell — do not edit\nlayout {}\n"
	for _, op := range []func() error{
		func() error { return ApplyWrite(gen, rendered) },
		func() error { return ApplyNiri(cfg, gen, rendered) },
		func() error { return UnapplyNiri(cfg, gen) },
		func() error { return ApplyGtkThemeName(ini, "sysc-shell-New") },
		func() error { return UnapplyGtkThemeName(ini) },
	} {
		if err := op(); err != nil {
			t.Fatal(err)
		}
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range entries {
			if strings.Contains(e.Name(), ".sysc-") {
				t.Fatalf("atomic write leaked %s", e.Name())
			}
		}
	}
	if content, err := os.ReadFile(gen); err == nil && !strings.Contains(string(content), "layout") {
		t.Fatalf("atomic replace lost content: %q", content)
	} // UnapplyNiri deletes gen, so absence is the expected final state.
}
