func TestReadOnlyNiriConfigIsReportedNotRewritten(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	cfg := filepath.Join(dir, "config.kdl")
	gen := filepath.Join(dir, "sysc-shell.kdl")
	if err := os.WriteFile(cfg, []byte("keybinds { }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(cfg, 0o444); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(cfg, 0o644) })
	if err := ApplyNiri(cfg, gen, "// generated by sysc-shell — do not edit\n"); err == nil {
		t.Fatal("read-only config must report failure")
	}
	got, _ := os.ReadFile(cfg)
	if string(got) != "keybinds { }\n" {
		t.Fatal("read-only config was modified")
	}
}
