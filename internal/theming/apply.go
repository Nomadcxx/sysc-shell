// directive is one single-line setting sysc-shell manages inside a user
// config file, without owning the file itself. State records distinguish a
// line inserted by the shell from an identical line already owned by the user.
type directive struct {
	file         string // user config path
	line         string // the exact line sysc-shell writes
	key          string // a line starting with this is ours or the user's
	section      string // ini/toml section the line must live under ("" = top level)
	seed         string // whole-file content when creating (empty = just the line)
	create       bool   // invent the file if it does not exist
	top          bool   // root-key zone: insert before the first table header
	returnConfig bool   // Lua assignment must precede a final `return config`
}

// EnsureDirective appends, updates or creates exactly one directive line.
// A pre-existing line with the same key that is not ours is the user's and
// is never touched.
func EnsureDirective(d directive) error {
	return ensureDirective(d, false)
}

func ensureDirective(d directive, force bool) error {
	b, err := os.ReadFile(d.file)
	if err != nil {
		if !os.IsNotExist(err) {
			return err
		}
		if !d.create {
			return nil
		}
		content := d.seed
		if content == "" {
			content = d.line + "\n"
		}
		if err := setDirectiveOwned(d, false); err != nil {
			return fmt.Errorf("clear stale directive ownership for %s: %w", d.file, err)
		}
		if err := writeFileAtomic(d.file, []byte(content), 0o644); err != nil {
			return err
		}
		return recordDirectiveOwned(d, nil, []byte(content), false)
	}
	lines := strings.Split(string(b), "\n")
	returnIndex, err := directiveReturnIndex(lines, d)
	if err != nil {
		return err
	}
	own := strings.TrimSpace(d.line)
	ownCount, conflictCount := 0, 0
	ownIndex := -1
	for _, ln := range lines {
		trim := strings.TrimSpace(ln)
		if trim == own {
			ownCount++
			continue
		}
		if directiveKeyMatches(trim, d.key) {
			conflictCount++
		}
	}
	for i, ln := range lines {
		if strings.TrimSpace(ln) == own {
			ownIndex = i
			break
		}
	}
	needsMove := d.returnConfig && ownCount == 1 && ownIndex >= returnIndex
	if needsMove && !directiveOwned(d) {
		return fmt.Errorf("%w: misplaced directive in %s", ErrUserModified, d.file)
	}
	if conflictCount == 0 && ownCount == 1 && !needsMove {
		return nil
	}
	if (conflictCount > 0 || ownCount > 1) && !force {
		return fmt.Errorf("%w: directive in %s", ErrUserModified, d.file)
	}
	if ownCount == 0 {
		if err := setDirectiveOwned(d, false); err != nil {
			return fmt.Errorf("clear stale directive ownership for %s: %w", d.file, err)
		}
	}
	if conflictCount == 0 && ownCount == 0 {
		content := directiveContent(b, lines, d)
		if err := writeDirectiveConfig(d.file, content); err != nil {
			return err
		}
		return recordDirectiveOwned(d, b, content, true)
	}
	if force {
		if err := backupUserFileOnce(d.file, b); err != nil {
			return err
		}
	}
	remaining := make([]string, 0, len(lines))
	for _, ln := range lines {
		trim := strings.TrimSpace(ln)
		if trim == own || directiveKeyMatches(trim, d.key) {
			continue
		}
		remaining = append(remaining, ln)
	}
	content := directiveContent([]byte(strings.Join(remaining, "\n")), remaining, d)
	if err := writeDirectiveConfig(d.file, content); err != nil {
		return err
	}
	return recordDirectiveOwned(d, b, content, true)
}

func directiveReturnIndex(lines []string, d directive) (int, error) {
	if !d.returnConfig {
		return -1, nil
	}
	for i := len(lines) - 1; i >= 0; i-- {
		trim := strings.TrimSpace(lines[i])
		if trim == "" || strings.HasPrefix(trim, "--") {
			continue
		}
		if trim != "return config" {
			break
		}
		return i, nil
	}
	return -1, fmt.Errorf("%w: WezTerm config must end with `return config`", ErrUserModified)
}

func directiveOwnershipKey(d directive) string {
	return "directive:" + hash([]byte(d.file+"\x00"+strings.TrimSpace(d.line)))
}

func directiveKeyMatches(line, key string) bool {
	trim := strings.TrimSpace(line)
	if strings.HasSuffix(key, "=") {
		name := strings.TrimSpace(strings.TrimSuffix(key, "="))
		if name == "" || !strings.HasPrefix(trim, name) {
			return false
		}
		return strings.HasPrefix(strings.TrimLeft(trim[len(name):], " \t"), "=")
	}
	return strings.HasPrefix(trim, key)
}

func directiveOwned(d directive) bool {
	return stateHash(directiveOwnershipKey(d)) == "owned"
}

func setDirectiveOwned(d directive, owned bool) error {
	value := ""
	if owned {
		value = "owned"
	}
	return rememberHash(directiveOwnershipKey(d), value)
}

func recordDirectiveOwned(d directive, before, written []byte, existed bool) error {
	if err := setDirectiveOwned(d, true); err != nil {
		cause := fmt.Errorf("record directive ownership for %s: %w", d.file, err)
		current, readErr := os.ReadFile(d.file)
		if errors.Is(readErr, os.ErrNotExist) {
			return cause
		}
		if readErr != nil {
			return errors.Join(cause, fmt.Errorf("check config before rollback: %w", readErr))
		}
		if !bytes.Equal(current, written) {
			return errors.Join(cause, fmt.Errorf("config changed before rollback; preserving %s", d.file))
		}
		var rollbackErr error
		if existed {
			rollbackErr = writeDirectiveConfig(d.file, before)
		} else {
			rollbackErr = os.Remove(d.file)
		}
		if rollbackErr != nil {
			return errors.Join(cause, fmt.Errorf("roll back config %s: %w", d.file, rollbackErr))
		}
		return cause
	}
	return nil
}

func directiveContent(body []byte, lines []string, d directive) []byte {
	if d.returnConfig {
		if index, err := directiveReturnIndex(lines, d); err == nil {
			out := make([]string, 0, len(lines)+1)
			out = append(out, lines[:index]...)
			out = append(out, d.line)
			out = append(out, lines[index:]...)
			return []byte(strings.Join(out, "\n"))
		}
	}
	if d.top && d.section == "" {
		for i, ln := range lines {
			trim := strings.TrimSpace(ln)
			if trim == blockOpen || strings.HasPrefix(trim, "[") {
				out := make([]string, 0, len(lines)+1)
				out = append(out, lines[:i]...)
				out = append(out, d.line)
				out = append(out, lines[i:]...)
				return []byte(strings.Join(out, "\n"))
			}
		}
	}
	if d.section == "" {
		if strings.TrimSpace(string(body)) == "" {
			return []byte(d.line + "\n")
		}
		out := strings.TrimSuffix(string(body), "\n") + "\n" + d.line + "\n"
		return []byte(out)
	}
	header := "[" + d.section + "]"
	for i, ln := range lines {
		if strings.TrimSpace(ln) == header {
			out := make([]string, 0, len(lines)+1)
			out = append(out, lines[:i+1]...)
			out = append(out, d.line)
			out = append(out, lines[i+1:]...)
			return []byte(strings.Join(out, "\n"))
		}
	}
	out := strings.TrimSuffix(string(body), "\n") + "\n\n" + header + "\n" + d.line + "\n"
	if strings.TrimSpace(string(body)) == "" {
		out = header + "\n" + d.line + "\n"
	}
	return []byte(out)
}

// backupUserFileOnce preserves the complete user config before a confirmed
// replacement, retaining its mode and the first backup.
func backupUserFileOnce(path string, data []byte) error {
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	backup := path + ".bak"
	f, err := os.OpenFile(backup, os.O_WRONLY|os.O_CREATE|os.O_EXCL, info.Mode().Perm())
	if errors.Is(err, os.ErrExist) {
		return nil
	}
	if err != nil {
		return err
	}
	cleanup := func(err error) error {
		_ = f.Close()
		_ = os.Remove(backup)
		return err
	}
	if err := f.Chmod(info.Mode().Perm()); err != nil {
		return cleanup(err)
	}
	if _, err := f.Write(data); err != nil {
		return cleanup(err)
	}
	if err := f.Sync(); err != nil {
		return cleanup(err)
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(backup)
		return err
	}
	return nil
}

func writeDirectiveConfig(path string, data []byte) error {
	mode := os.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	} else if !os.IsNotExist(err) {
		return err
	}
	return writeFileAtomic(path, data, mode)
}

// RemoveDirective deletes only the exact line sysc-shell wrote and refuses
// to leave an unowned or edited directive with the same key. A file left with
// nothing but blank lines is removed.
func RemoveDirective(d directive) error {
	owned := directiveOwned(d)
	b, err := os.ReadFile(d.file)
	if err != nil {
		if os.IsNotExist(err) {
			if owned {
				return setDirectiveOwned(d, false)
			}
			return nil
		}
		return err
	}
	own := strings.TrimSpace(d.line)
	var keep []string
	removed := false
	matchingKey := false
	for _, ln := range strings.Split(string(b), "\n") {
		trim := strings.TrimSpace(ln)
		if directiveKeyMatches(trim, d.key) {
			if owned && !removed {
				if trim == own {
					removed = true
					continue
				}
			}
			matchingKey = true
		}
		keep = append(keep, ln)
	}
	if !owned {
		if matchingKey {
			return fmt.Errorf("%w: unowned directive in %s", ErrUserModified, d.file)
		}
		return nil
	}
	if !removed {
		if err := setDirectiveOwned(d, false); err != nil {
			return err
		}
		if matchingKey {
			return fmt.Errorf("%w: modified directive in %s", ErrUserModified, d.file)
		}
		return nil
	}
	if err := setDirectiveOwned(d, false); err != nil {
		return err
	}
	if strings.TrimSpace(strings.Join(keep, "\n")) == "" {
		if err := removeOrEmpty(d.file); err != nil {
			_ = setDirectiveOwned(d, true)
			return err
		}
		return nil
	}
	if err := writeDirectiveConfig(d.file, []byte(strings.Join(keep, "\n"))); err != nil {
		_ = setDirectiveOwned(d, true)
		return err
	}
	if matchingKey {
		return fmt.Errorf("%w: additional directive in %s", ErrUserModified, d.file)
	}
	return nil
}

// ManageBlock writes body between the open and close marker lines,
// replacing a previous managed block or appending a new one. The markers are
// sysc-shell-specific; only a block whose saved bytes still match is updated.
func ManageBlock(file, open, close, body string, force bool) error {
	block := managedBlockLines(open, close, body)
	key := managedBlockKey(file, open, close)
	b, err := os.ReadFile(file)
	if err != nil {
		if !os.IsNotExist(err) {
			return err
		}
		if err := writeDirectiveConfig(file, []byte(strings.Join(block, "\n")+"\n")); err != nil {
			return err
		}
		_ = rememberHash(key, hash([]byte(strings.Join(block, "\n"))))
		return nil
	}
	lines := strings.Split(string(b), "\n")
	start, end := -1, -1
	for i, ln := range lines {
		switch strings.TrimSpace(ln) {
		case open:
			if start >= 0 {
				return fmt.Errorf("skipped: two sysc-shell blocks in %s", file)
			}
			start = i
		case close:
			if start < 0 || end >= 0 {
				return fmt.Errorf("skipped: stray sysc-shell block end in %s", file)
			}
			end = i
		}
	}
	if start >= 0 && end < start {
		return fmt.Errorf("skipped: unbalanced sysc-shell block in %s", file)
	}
	if start >= 0 {
		oldBlock := []byte(strings.Join(lines[start:end+1], "\n"))
		if stateHash(key) != hash(oldBlock) {
			if !force {
				return fmt.Errorf("%w: managed block in %s", ErrUserModified, file)
			}
			if err := backupUserFileOnce(file, b); err != nil {
				return err
			}
		}
	}
	var out []string
	if start < 0 {
		out = append(out, lines...)
		if len(out) > 0 && strings.TrimSpace(out[len(out)-1]) == "" {
			out = out[:len(out)-1]
		}
		if len(out) > 0 {
			out = append(out, "")
		}
		out = append(out, block...)
	} else {
		out = append(out, lines[:start]...)
		out = append(out, block...)
		out = append(out, lines[end+1:]...)
	}
	if err := writeDirectiveConfig(file, []byte(strings.Join(out, "\n")+"\n")); err != nil {
		return err
	}
	_ = rememberHash(key, hash([]byte(strings.Join(block, "\n"))))
	return nil
}

// RemoveBlock deletes the managed block including its marker lines.
func RemoveBlock(file, open, close string, force bool) error {
	b, err := os.ReadFile(file)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	lines := strings.Split(string(b), "\n")
	start, end := -1, -1
	for i, ln := range lines {
		switch strings.TrimSpace(ln) {
		case open:
			if start >= 0 {
				return fmt.Errorf("skipped: two sysc-shell blocks in %s", file)
			}
			start = i
		case close:
			if start < 0 || end >= 0 {
				return fmt.Errorf("skipped: stray sysc-shell block end in %s", file)
			}
			end = i
		}
	}
	if start < 0 {
		return nil
	}
	if end < start {
		return fmt.Errorf("skipped: unterminated sysc-shell block in %s", file)
	}
	key := managedBlockKey(file, open, close)
	oldBlock := []byte(strings.Join(lines[start:end+1], "\n"))
	if stateHash(key) != hash(oldBlock) {
		if !force {
			return fmt.Errorf("%w: managed block in %s", ErrUserModified, file)
		}
		if err := backupUserFileOnce(file, b); err != nil {
			return err
		}
	}
	out := append(append([]string{}, lines[:start]...), lines[end+1:]...)
	if strings.TrimSpace(strings.Join(out, "\n")) == "" {
		return removeOrEmpty(file)
	}
	return writeDirectiveConfig(file, []byte(strings.Join(out, "\n")))
}

func removeOrEmpty(path string) error {
	info, err := os.Lstat(path)
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return writeDirectiveConfig(path, nil)
	}
	return os.Remove(path)
}

func managedBlockLines(open, close, body string) []string {
	block := strings.Split(strings.TrimSuffix(body, "\n"), "\n")
	return append(append([]string{open}, block...), close)
}

func managedBlockKey(file, open, close string) string {
	return file + "\x00sysc-shell-block\x00" + open + "\x00" + close
}
