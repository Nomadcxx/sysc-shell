// markTemplatesComplete lets mechanism tests exercise the write path of a
// template the release has not verified yet (GH #7 gate).
func markTemplatesComplete(t *testing.T, names ...string) {
	t.Helper()
	for _, n := range names {
		if !completeTemplates[n] {
			completeTemplates[n] = true
			t.Cleanup(func() { delete(completeTemplates, n) })
		}
	}
}

func TestApplyEnabledReportsRefusalsPerTemplate(t *testing.T) {
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	home := t.TempDir()
	markTemplatesComplete(t, "cava")
	target := filepath.Join(home, ".config", "cava", "config")
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(target, []byte("[color]\ntheme = user-choice\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	only := func(name string) bool { return name == "cava" }
	// An enabled template is applied over the user's own value (owner
	// decision, 2026-10-09), and the takeover is reported.
	outcomes, adopted, err := ApplyEnabled(home, only, theme.Fallback, 100)
	if err != nil || len(outcomes) != 0 {
		t.Fatalf("apply = %v, %v; want the template adopted", outcomes, err)
	}
	if !slices.Equal(adopted, []string{"cava"}) {
		t.Fatalf("adopted = %v, want cava", adopted)
	}
	if backup, _ := os.ReadFile(target + ".bak"); string(backup) != "[color]\ntheme = user-choice\n" {
		t.Fatalf("backup = %q, want the user's file", backup)
	}
	// Once the shell owns the setting, a re-apply adopts nothing.
	if _, again, err := ApplyEnabled(home, only, theme.Fallback, 100); err != nil || len(again) != 0 {
		t.Fatalf("re-apply adopted %v, err %v", again, err)
	}
	if got, _ := os.ReadFile(target); string(got) != "[color]\ntheme = \"sysc-shell\"\n" {
		t.Fatalf("forced directive replacement = %q", got)
	}
	if backup, err := os.ReadFile(target + ".bak"); err != nil || string(backup) != "[color]\ntheme = user-choice\n" {
		t.Fatalf("refused config backup = %q, %v", backup, err)
	}
}

