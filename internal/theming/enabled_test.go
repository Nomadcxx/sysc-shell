func TestApplyEnabledAndWaitReturnsItsQueuedOutcome(t *testing.T) {
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	home1 := t.TempDir()
	home2 := t.TempDir()
	markTemplatesComplete(t, "alacritty", "foot")
	footSidecar := filepath.Join(home2, ".config", "foot", "themes", "sysc-shell")
	if err := os.MkdirAll(filepath.Dir(footSidecar), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(footSidecar, []byte("user edit\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	started := make(chan struct{})
	block := make(chan struct{})
	defer func() {
		select {
		case <-block:
		default:
			close(block)
		}
	}()
	first := func(name string) bool {
		if name != "alacritty" {
			return false
		}
		select {
		case <-started:
		default:
			close(started)
		}
		<-block
		return true
	}
	firstDone := make(chan struct{})
	go func() {
		_, _, _ = ApplyEnabled(home1, first, theme.Fallback, 100)
		close(firstDone)
	}()
	select {
	case <-started:
	case <-time.After(2 * time.Second):
		t.Fatal("first apply did not reach alacritty")
	}

	type result struct {
		outcomes map[string]error
		adopted  []string
		err      error
	}
	secondDone := make(chan result, 1)
	go func() {
		outcomes, adopted, err := ApplyEnabledAndWait(home2, func(name string) bool { return name == "foot" }, theme.Fallback, 100)
		secondDone <- result{outcomes: outcomes, adopted: adopted, err: err}
	}()
	deadline := time.After(2 * time.Second)
	for {
		applyMu.Lock()
		queued := applyQueued != nil
		applyMu.Unlock()
		if queued {
			break
		}
		select {
		case <-deadline:
			t.Fatal("second apply was not queued")
		case <-time.After(time.Millisecond):
		}
	}

	close(block)
	select {
	case <-firstDone:
	case <-time.After(2 * time.Second):
		t.Fatal("first apply did not finish")
	}
	select {
	case got := <-secondDone:
		// The queued apply returns its own outcome: foot, adopted over the
		// edited sidecar.
		if footErr, attempted := got.outcomes["foot"]; !attempted || footErr != nil || got.err != nil {
			t.Fatalf("second outcomes = %v, err = %v; want foot attempted and applied", got.outcomes, got.err)
		}
		if !slices.Equal(got.adopted, []string{"foot"}) {
			t.Fatalf("second adopted = %v, want foot", got.adopted)
		}
	case <-time.After(2 * time.Second):
		t.Fatal("second apply did not return its outcome")
	}
}

