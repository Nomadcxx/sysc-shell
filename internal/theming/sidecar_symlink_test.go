// A user keeps a template sidecar symlinked into a dotfiles repo. The shell
// must write through the link: a rename over the link would replace the link
// itself, and the dotfile would keep the palette the shell thought it had
// changed.
func TestSidecarWritePreservesSymlink(t *testing.T) {
	t.Setenv("XDG_STATE_HOME", t.TempDir())
	home := t.TempDir()

	sidecar := filepath.Join(home, ".config", "alacritty", "themes", "sysc-shell.toml")
	if err := os.MkdirAll(filepath.Dir(sidecar), 0o755); err != nil {
		t.Fatal(err)
	}
	real := filepath.Join(home, "dotfiles", "alacritty-theme.toml")
	if err := os.MkdirAll(filepath.Dir(real), 0o755); err != nil {
		t.Fatal(err)
	}
	user := "# user owns this file\n"
	if err := os.WriteFile(real, []byte(user), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(real, sidecar); err != nil {
		t.Fatal(err)
	}

	rendered := "# generated by sysc-shell\n[colors.primary]\nbackground = '#101010'\n"
	if err := applySidecar(sidecar, rendered, true); err != nil {
		t.Fatalf("applySidecar: %v", err)
	}
	info, err := os.Lstat(sidecar)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("apply replaced the sidecar symlink with a regular file (mode %v)", info.Mode())
	}
	body, err := os.ReadFile(real)
	if err != nil {
		t.Fatal(err)
	}
	if string(body) != rendered {
		t.Fatalf("link target = %q, want %q", body, rendered)
	}
	// The user's own bytes are kept in the backup, so the overwrite can be
	// undone without the link moving.
	backup, err := os.ReadFile(sidecar + ".bak")
	if err != nil {
		t.Fatalf("backup: %v", err)
	}
	if string(backup) != user {
		t.Fatalf("backup = %q, want %q", backup, user)
	}
}

